/*
    Builds nutrition-data.js from a Livsmedelsverket export.

        node tools/build-nutrition.js <export-file>

    <export-file> is the same file the audit takes — the .xlsx from Sök
    näringsinnehåll, or a CSV or JSON export.

    If you'd rather not use a terminal, tools/build-nutrition.html does the
    same thing in a browser and works fine on a phone. Both go through
    nutrition-core.js, so they cannot produce different files.
*/

const fs = require("fs");
const path = require("path");
const LMV = require("./lmv-core.js");
const NutritionCore = require("./nutrition-core.js");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "nutrition-data.js");

function loadFoods() {
    const src = fs.readFileSync(path.join(ROOT, "foods-data.js"), "utf8");
    const { CATEGORIES } = new Function(src + "; return { CATEGORIES };")();
    return LMV.flattenCategories(CATEGORIES);
}

/* Everything below Livsmedelsverket on the source ladder, in one object.
   Frida (Denmark, generated by tools/frida-audit.js) sits above the
   hand-entered file, which holds USDA and Ciqual entries typed in one at a
   time — a national table read whole beats figures copied by hand. Same
   files the browser builder reads. */
function loadFallbacks() {
    function read(file, symbol) {
        const p = path.join(ROOT, file);
        if (!fs.existsSync(p)) return {};
        return new Function(fs.readFileSync(p, "utf8") + "; return " + symbol + ";")() || {};
    }
    /* Later wins, so this is the ladder upside down: hand-typed figures are
       the weakest, then USDA, then Ciqual, then Frida.

       A national table read whole beats figures copied by hand. Denmark beats
       everyone below it because it describes food off the same shelf as
       Sweden. France beats America because it is a European table for a
       European diet, and because where the two overlap America is answering
       about a different shelf — but it sits below Denmark, since Ciqual
       carries no confidence code per figure and so cannot be tested value by
       value the way the American set is.

       Livsmedelsverket beats all four, in nutrition-core.js. */
    return Object.assign(
        {},
        read("nutrition-manual.js", "NUTRITION_MANUAL"),
        read("nutrition-usda.js", "NUTRITION_USDA"),
        read("nutrition-ciqual.js", "NUTRITION_CIQUAL"),
        read("nutrition-frida.js", "NUTRITION_FRIDA")
    );
}

/* The extras rungs, in the same order and for the same reason. These carry
   lactose and polyols for foods Livsmedelsverket already answers — the two
   columns it does not publish for anything. Same file, separate symbol, so a
   borrowed column can never be mistaken for a full match. */
function loadExtras() {
    function read(file, symbol) {
        const p = path.join(ROOT, file);
        if (!fs.existsSync(p)) return {};
        const text = fs.readFileSync(p, "utf8");
        if (!new RegExp("(^|[\\s;])(const|let|var)\\s+" + symbol + "\\s*=").test(text)) return {};
        return new Function(text + "; return " + symbol + ";")() || {};
    }
    return Object.assign(
        {},
        read("nutrition-ciqual.js", "NUTRITION_CIQUAL_EXTRAS"),
        read("nutrition-frida.js", "NUTRITION_FRIDA_EXTRAS")
    );
}

function loadMap(name) {
    const p = path.join(__dirname, name);
    if (!fs.existsSync(p)) return {};
    const raw = JSON.parse(fs.readFileSync(p, "utf8"));
    const out = {};
    Object.keys(raw).forEach(function (k) { if (k[0] !== "_") out[k] = raw[k]; });
    return out;
}

function main() {
    const file = process.argv.slice(2).find(function (a) { return a[0] !== "-"; });
    if (!file) {
        console.error("usage: node tools/build-nutrition.js <export-file>");
        process.exit(1);
    }

    const ours = loadFoods();
    const aliases = loadMap("lmv-aliases.json");
    const swedish = loadMap("lmv-swedish.json");
    const absent = loadMap("lmv-absent.json");

    const load = /\.xlsx$/i.test(file)
        ? LMV.parseXlsx(fs.readFileSync(file).buffer)
        : Promise.resolve(LMV.parseExport(fs.readFileSync(file, "utf8")));

    load.then(function (lmv) {
        const result = LMV.runAudit(ours, lmv, aliases, swedish, absent);
        const manual = loadFallbacks();
        const built = NutritionCore.build(
            result, ours.length, path.basename(file), manual, loadExtras());

        fs.writeFileSync(OUT, built.text, "utf8");

        console.log("Nutrients detected: " + Object.keys(result.detected).join(", "));
        console.log("Wrote " + built.rows.length + " of " + ours.length + " foods to nutrition-data.js" +
            " (" + built.manualUsed + " from below Livsmedelsverket on the ladder)");
        console.log("No Livsmedelsverket entry: " + built.skipped);
        if (built.borrowed.length) {
            console.log("Borrowed columns (lactose and polyols only): " + built.borrowed.length);
        }
        if (built.unmatched.length) {
            console.log("Unmatched (no figures, and not on the absent list): " + built.unmatched.length);
            built.unmatched.forEach(function (n) { console.log("  " + n); });
        }
        if (built.empty.length) {
            console.log("Matched but the export carried no usable figures: " + built.empty.length);
            built.empty.forEach(function (n) { console.log("  " + n); });
        }
    }).catch(function (err) {
        console.error("Could not read " + file + ": " + err.message);
        process.exit(1);
    });
}

main();
